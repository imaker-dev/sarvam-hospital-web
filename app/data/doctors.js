export const getDoctors = () => {
  return doctors.map(({ id, slug, card }) => ({
    id,
    slug,
    ...card,
  }));
};

export const getDoctorBySlug = (idOrSlug) => {
  const doctor = doctors.find(
    (doctor) => doctor.id === idOrSlug || doctor.slug === idOrSlug,
  );

  if (!doctor) return null;

  return {
    id: doctor.id,
    slug: doctor.slug,
    ...doctor.details,
  };
};
