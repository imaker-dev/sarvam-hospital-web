// Get all blog cards for the listing page
export const getBlogs = () => {
  return blogs.map(({ id, slug, card }) => ({
    id,
    slug,
    ...card,
  }));
};

// Get blog details by ID or slug
export const getBlogDetails = (idOrSlug) => {
  const blog = blogs.find(
    ({ id, slug }) => id === idOrSlug || slug === idOrSlug,
  );

  if (!blog) return null;

  return {
    id: blog.id,
    slug: blog.slug,
    ...blog.details,
  };
};